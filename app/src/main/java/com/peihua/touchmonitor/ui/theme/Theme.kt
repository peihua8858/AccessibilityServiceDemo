/**
 * 按设备最小宽度（smallestScreenWidthDp）返回温和且封顶的全局 UI 缩放系数。
 *
 * 用 smallestScreenWidthDp 而非 screenWidthDp：前者反映设备物理尺寸、横竖屏一致，
 * 后者会随方向变化导致竖屏偏小。覆盖 LocalDensity 后，字体、间距、圆角、图标等
 * dp/sp 尺寸按此比例统一放大——大屏协调放大，且避免老式 values-sw*dp 线性表的失衡。
 */
private fun uiScaleForWidth(smallestWidthDp: Int): Float = when {
    smallestWidthDp < 600 -> 1.0f   // 手机
    smallestWidthDp < 672 -> 1.20f  // 小平板 / 折叠展开
    smallestWidthDp < 768 -> 1.30f  // 7~8 寸平板（本机 720dp）
    smallestWidthDp < 960 -> 1.40f  // 10 寸平板
    else -> 1.50f                    // 超大屏封顶
}



@Composable
fun Theme(
    darkTheme: Boolean,
    dynamicColor: Boolean,
    content: @Composable (isDark: Boolean, colorScheme: ColorScheme) -> Unit,
) {
    val dynamicColorScheme = if (dynamicColor) dynamicColorScheme(darkTheme) else null
    val colorScheme = when {
        dynamicColorScheme != null -> dynamicColorScheme
        darkTheme -> darkScheme
        else -> lightScheme
    }
    val baseDensity = LocalDensity.current
    val uiScale = uiScaleForWidth(LocalConfiguration.current.smallestScreenWidthDp)
    val scaledDensity = Density(
        density = baseDensity.density * uiScale,
        fontScale = baseDensity.fontScale,
    )
    CompositionLocalProvider(
        LocalDensity provides scaledDensity,
        LocalToolColors provides DefaultToolColors,
    ) {
        MaterialTheme(
            shapes = customShapes,
            colorScheme = colorScheme,
            typography = AppTypography,
        ) {
            CompositionLocalProvider(
                LocalScrollbarStyle provides ScrollbarStyle(
                    minimalHeight = 16.dp,
                    thickness = 8.dp,
                    scrollbarPadding = 16.dp,
                    shape = RoundedCornerShape(4.dp),
                    hoverDurationMillis = 500,
                    hideDelayMillis = 2000,
                    unhoverColor = colorScheme.outlineVariant,
                    hoverColor = colorScheme.outline,
                )
            ) {
                ProvideTextStyle(value = DefaultTextStyle) {
                    content(darkTheme, colorScheme)
                }
            }
        }
    }
}

@Composable
private fun dynamicColorScheme(isDarkTheme: Boolean): ColorScheme? {
    return if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
        val context = LocalContext.current
        if (isDarkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
    } else null
}

@Composable
fun AppTheme(
    config: ThemeModel,
    content: @Composable (isDark: Boolean, colorScheme: ColorScheme) -> Unit,
) {
    val isDark = when (config.theme) {
        ThemeMode.System -> isSystemInDarkTheme()
        ThemeMode.Light -> false
        ThemeMode.Dark -> true
    }
    Theme(
        darkTheme = isDark,
        dynamicColor = config.dynamicColor,
        content = content,
    )
}

